import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

const sections = ["helpers", "observation", "inspection", "verification", "filling"];
const destination = new URL("form-dom.js", import.meta.url);
export function generateFormDOM({ check = false } = {}) {
  const source = "// Generated by generate-form-dom.mjs; edit form-dom/*.jsfrag.\n" +
    sections.map((section) => readFileSync(new URL(`form-dom/${section}.jsfrag`, import.meta.url), "utf8")).join("");
  if (check) {
    if (readFileSync(destination, "utf8") !== source)
      throw new Error("form_dom_generated_drift: run pnpm -C extension dom:generate");
  } else writeFileSync(destination, source);
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  if (process.argv.slice(2).some((arg) => arg !== "--check"))
    throw new Error("Only --check is supported");
  generateFormDOM({ check: process.argv.includes("--check") });
}
